const FULL_CLUB = { 'Реал': 'Реал Мадрид', 'Сіті': 'Манчестер Сіті', 'Динамо': 'Динамо Київ' };
export function clubFit(character, club) {
  const row = CHARACTERS.find((c) => c[0] === character);
  if (!row) return ['нейтрально', 'neutral'];
  const full = (list) => list.map((n) => FULL_CLUB[n] || n);
  if (full(row[4]).includes(club)) return ['твій', 'own'];
  if (full(row[5]).includes(club)) return ['чужий', 'foreign'];
  return ['нейтрально', 'neutral'];
}

